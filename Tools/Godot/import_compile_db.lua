-- Convert an audited SCons baseline; production builds never read SCons state.
function stage(source)
    if source:startswith("modules/dora_bridge/") then return "godot-dora-bridge" end
    return ({drivers = "godot-drivers", servers = "godot-servers", scene = "godot-scene", modules = "godot-modules",
        main = "godot-main-platform", platform = "godot-main-platform"})[source:match("^[^/]+") or source] or "godot-core"
end

function parse(entry, include_roots, macos)
    -- os.argv implements POSIX shell quoting, including quoted macro values.
    local args = os.argv(entry.command)
    local source = entry.file:gsub("\\", "/")
    local flags, seen, sdk, index = {}, {}, nil, 2
    local ios, web = table.contains(args, "-DIOS_ENABLED"), table.contains(args, "-DWEB_ENABLED")
    if ios then for i, arg in ipairs(args) do if arg == "-isysroot" then sdk = args[i + 1] end end end
    while index <= #args do
        local arg, skip = args[index], false
        if table.contains(macos and {"-o", "-arch", "-isysroot"} or {"-o", "-arch", "-isysroot", "-target", "--target", "--sysroot"}, arg)
            or (ios and arg == "-MT") then index = index + 1; skip = true
        elseif arg == "-c" or arg == source or arg == "-std=gnu17" or arg == "-std=gnu++17"
            or arg:startswith("-mmacosx-version-min=") or arg:startswith("-O") or arg == "-fno-color-diagnostics"
            or (not macos and (arg == "-fno-diagnostics-color" or arg:startswith("--target=") or arg:startswith("--sysroot=")))
            or (ios and (arg == "-MMD" or arg:startswith("-mios-simulator-version-min=") or arg:startswith("-miphoneos-version-min="))) then skip = true
        end
        if not skip then
            if sdk and arg:startswith("-I" .. sdk .. "/") then arg = "-I@SDK@/" .. arg:sub(#sdk + 4) end
            for option, root in pairs(include_roots or {}) do
                if arg:startswith("-I" .. root .. "/") then arg = "-I@CONFIG:" .. option .. "@/" .. arg:sub(#root + 4); break end
            end
            if web and arg:startswith("-I") and arg:find("/cache/sysroot/", 1, true) then skip = true end
            if not skip then
                if arg:startswith("-I") and #arg > 2 and not arg:startswith("-I@") and not path.is_absolute(arg:sub(3)) then arg = "-I@GODOT@/" .. arg:sub(3) end
                if not arg:startswith("-I") or not seen[arg] then flags[#flags + 1] = arg end
                if arg:startswith("-I") then seen[arg] = true end
            end
        end
        index = index + 1
    end
    if source:find(".gen.", 1, true) then flags[#flags + 1] = "-I@GODOT@/" .. (source:match("^(.*)/") or ".") end
    local suffix = path.extension(source)
    local language = ({[".m"] = "mflags", [".mm"] = "mxxflags"})[suffix]
        or (not macos and suffix:lower() == ".s" and "asflags") or (args[1]:endswith("++") and "cxxflags" or "cflags")
    return stage(source), flags, language
end

function convert(compile_db, output, args, macos)
    local C = import("common", {rootdir = os.scriptdir()})
    local V = import("native_variants", {rootdir = os.scriptdir()})
    local generated = args["generated-root"] or "build/godot-xmake/generated"
    assert(not path.is_absolute(generated), "Generated root must remain project-relative")
    local roots = {}
    for _, value in ipairs(args["include-root"] or {}) do
        local name, directory = value:match("^([a-z][a-z0-9_]*)=(.+)$")
        assert(name and path.is_absolute(directory), "--include-root requires a lowercase xmake option and an absolute root")
        roots[name] = directory:gsub("[/\\]+$", "")
    end
    local entries = C.load(compile_db)
    local counts, groups = {}, {}
    for _, entry in ipairs(entries) do local source = entry.file:gsub("\\", "/"); counts[source] = (counts[source] or 0) + 1 end
    for _, entry in ipairs(entries) do
        local target, flags, language = parse(entry, roots, macos)
        local source = entry.file:gsub("\\", "/")
        if counts[source] > 1 then target = V.variant_target(source, flags) end
        local key = target .. "\0" .. language .. "\0" .. table.concat(flags, "\0")
        groups[key] = groups[key] or {target = target, flags = flags, language = language, files = {}}
        table.insert(groups[key].files, source)
    end
    local function quote(value) import("core.base.json"); return (json.encode(value):gsub("\\/", "/")) end
    local lines = {
        "-- Generated by Tools/Godot/import_compile_db.lua from an audited SCons baseline.",
        "-- This manifest is a migration input; production xmake builds do not read SCons state.",
        'local godot_root = path.join(os.projectdir(), "Source/3rdParty/Godot")',
        'local generated_root = DORA_GODOT_GENERATED_ROOT or path.join(os.projectdir(), ' .. quote(generated) .. ')',
        'local function source(relative)',
        '    local project_prefix = "@PROJECT@/"',
        '    if relative:sub(1, #project_prefix) == project_prefix then',
        '        return path.join(os.projectdir(), relative:sub(#project_prefix + 1))',
        '    end',
        '    if relative:find(".gen.", 1, true) then',
        '        -- Relative DSL paths preserve file flags before the generated file exists.',
        '        return path.relative(path.join(generated_root, relative), os.scriptdir())',
        '    end', '    return path.join(godot_root, relative)', 'end', 'local function flag(value)',
        '    if is_mode("debug") and value == "-DNDEBUG" then return "-DDEBUG_ENABLED" end'}
    for _, name in ipairs(C.keys(roots)) do
        table.join2(lines, {'    local external_prefix = ' .. quote("-I@CONFIG:" .. name .. "@/"),
            '    if value:sub(1, #external_prefix) == external_prefix then', '        local root = get_config(' .. quote(name) .. ') or ""',
            '        return "-I" .. path.join(root, value:sub(#external_prefix + 1))', '    end'})
    end
    table.join2(lines, {'    local prefix = "-I@GODOT@/"', '    if value:sub(1, #prefix) == prefix then',
        '        return "-I" .. path.join(godot_root, value:sub(#prefix + 1))', '    end', '    return value', 'end', ''})
    local ordered = {}; for _, group in pairs(groups) do ordered[#ordered + 1] = group end
    table.sort(ordered, function (a, b)
        if a.target ~= b.target then return a.target < b.target end
        if a.language ~= b.language then return a.language < b.language end
        return a.files[1] < b.files[1]
    end)
    for _, group in ipairs(ordered) do
        table.sort(group.files)
        for offset = 1, #group.files, 64 do
            table.join2(lines, {'target(' .. quote(group.target) .. ')', '    add_files('})
            for i = offset, math.min(offset + 63, #group.files) do lines[#lines + 1] = '        source(' .. quote(group.files[i]) .. '),' end
            lines[#lines + 1] = '        {' .. group.language .. ' = {'
            for _, flag in ipairs(group.flags) do lines[#lines + 1] = '            flag(' .. quote(flag) .. '),' end
            table.join2(lines, {'        }, always_added = true}', '    )', 'target_end()', ''})
        end
    end
    C.write(output, table.concat(lines, "\n"))
    print("wrote %d compile actions, %d unique sources and %d flag groups to %s", #entries, #C.keys(counts), #ordered, output)
end

function main(...)
    local C = import("common", {rootdir = os.scriptdir()})
    local args = C.args({...}, {variant = "value", ["object-platform"] = "value", ["generated-root"] = "value", ["include-root"] = "many"})
    assert(#args.positional == 2, "Usage: xmake lua import_compile_db.lua DB OUTPUT --variant NAME --object-platform NAME")
    C.required(args, "variant"); C.required(args, "object-platform")
    convert(args.positional[1], args.positional[2], args)
end
