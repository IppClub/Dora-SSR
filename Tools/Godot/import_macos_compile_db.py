#!/usr/bin/env python3
"""Convert the audited SCons macOS compile DB into a standalone xmake manifest."""

from __future__ import annotations

import argparse
import json
import shlex
import shutil
from collections import defaultdict
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
GODOT = ROOT / "Source/3rdParty/Godot"
WRAPPERS = ROOT / "Projects/xmake/godot/wrappers/macos_arm64"


def lua(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def stage(source: str) -> str:
    if source.startswith("modules/dora_bridge/"):
        return "godot-dora-bridge"
    top = source.split("/", 1)[0]
    return {
        "drivers": "godot-drivers",
        "servers": "godot-servers",
        "scene": "godot-scene",
        "modules": "godot-modules",
        "main": "godot-main-platform",
        "platform": "godot-main-platform",
    }.get(top, "godot-core")


def parse(entry: dict[str, str]) -> tuple[str, tuple[str, ...], str]:
    args = shlex.split(entry["command"])
    compiler = Path(args[0]).name
    source = entry["file"].replace("\\", "/")
    flags: list[str] = []
    index = 1
    while index < len(args):
        arg = args[index]
        if arg in {"-o", "-arch", "-isysroot"}:
            index += 2
            continue
        if arg == "-c" or arg == source:
            index += 1
            continue
        if arg in {"-std=gnu17", "-std=gnu++17"}:
            index += 1
            continue
        if arg.startswith(("-mmacosx-version-min=", "-O")) or arg == "-fno-color-diagnostics":
            index += 1
            continue
        if arg.startswith("-I") and len(arg) > 2 and not Path(arg[2:]).is_absolute():
            arg = "-I@GODOT@/" + arg[2:]
        flags.append(arg)
        index += 1
    suffix = Path(source).suffix
    # SCons generates these files in the original source tree, so quoted
    # includes find neighboring non-generated headers implicitly. XMAKE-02
    # keeps generated output under build/; retain the original parent as an
    # explicit include directory when importing the compile command.
    if ".gen." in source:
        flags.append("-I@GODOT@/" + str(Path(source).parent).replace("\\", "/"))
    if suffix == ".m":
        language = "mflags"
    elif suffix == ".mm":
        language = "mxxflags"
    else:
        language = "cxxflags" if compiler.endswith("++") else "cflags"
    return stage(source), tuple(flags), language


def wrapper_source(entry: dict[str, str]) -> str:
    args = shlex.split(entry["command"])
    output = Path(args[args.index("-o") + 1]).name
    variant = output.split(".macos.", 1)[0]
    original = Path(entry["file"].replace("\\", "/"))
    wrapper = WRAPPERS / original.parent / f"{variant}{original.suffix}"
    wrapper.parent.mkdir(parents=True, exist_ok=True)
    wrapper.write_text(f'#include "{original.as_posix()}"\n', encoding="utf-8")
    return "@PROJECT@/" + wrapper.relative_to(ROOT).as_posix()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("compile_db", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    entries = json.loads(args.compile_db.read_text(encoding="utf-8"))
    source_counts = Counter(entry["file"].replace("\\", "/") for entry in entries)
    if WRAPPERS.exists():
        shutil.rmtree(WRAPPERS)
    groups: dict[tuple[str, tuple[str, ...], str], list[str]] = defaultdict(list)
    for entry in entries:
        key = parse(entry)
        source = entry["file"].replace("\\", "/")
        if source_counts[source] > 1:
            source = wrapper_source(entry)
        groups[key].append(source)

    lines = [
        "-- Generated by Tools/Godot/import_macos_compile_db.py from the audited 4.6-stable SCons baseline.",
        "-- This manifest is a migration input; production xmake builds do not read SCons state.",
        'local godot_root = path.join(os.projectdir(), "Source/3rdParty/Godot")',
        'local generated_root = path.join(os.projectdir(), "build/godot-xmake/generated")',
        "local function source(relative)",
        '    local project_prefix = "@PROJECT@/"',
        "    if relative:sub(1, #project_prefix) == project_prefix then",
        "        return path.join(os.projectdir(), relative:sub(#project_prefix + 1))",
        "    end",
        '    if relative:find(".gen.", 1, true) then',
        "        return path.join(generated_root, relative)",
        "    end",
        "    return path.join(godot_root, relative)",
        "end",
        "local function flag(value)",
        '    local prefix = "-I@GODOT@/"',
        "    if value:sub(1, #prefix) == prefix then",
        '        return "-I" .. path.join(godot_root, value:sub(#prefix + 1))',
        "    end",
        "    return value",
        "end",
        "",
    ]
    for (target_name, flags, language), files in sorted(groups.items(), key=lambda item: (item[0][0], item[0][2], item[1][0])):
        ordered = sorted(files)
        for offset in range(0, len(ordered), 64):
            lines.append(f'target({lua(target_name)})')
            lines.append("    add_files(")
            for filename in ordered[offset : offset + 64]:
                lines.append(f"        source({lua(filename)}),")
            lines.append(f"        {{{language} = {{")
            for flag in flags:
                lines.append(f"            flag({lua(flag)}),")
            lines.append("        }}")
            lines.append("    )")
            lines.append("target_end()")
            lines.append("")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(entries)} sources in {len(groups)} flag groups to {args.output}")


if __name__ == "__main__":
    main()
