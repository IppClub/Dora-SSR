package("dora-webview2")
    set_homepage("https://developer.microsoft.com/microsoft-edge/webview2/")
    set_description("WebView2 SDK headers and static loader only; uses the installed Evergreen Runtime")
    set_license("Microsoft")
    add_urls("https://api.nuget.org/v3-flatcontainer/microsoft.web.webview2/$(version)/microsoft.web.webview2.$(version).nupkg", {filename = "webview2-$(version).zip"})
    add_versions("1.0.2903.40", "ef128016dd1e51c59178c827ed5b8aa3322c57afa8675d930f8109505542ad74")
    add_links("WebView2LoaderStatic")
    add_syslinks("ole32", "version", "advapi32", "shlwapi")
    on_install("windows", function (package)
        local arch = ({x86 = "x86", x64 = "x64", arm64 = "arm64"})[package:arch()]
        assert(arch, "Unsupported WebView2 architecture: " .. package:arch())
        os.cp("build/native/include/*.h", package:installdir("include"))
        os.cp("build/native/" .. arch .. "/WebView2LoaderStatic.lib", package:installdir("lib"))
    end)
package_end()
